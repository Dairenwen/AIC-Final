#!/usr/bin/env python3
"""Synchronize and verify the active-paper Elasticsearch index without model calls.

This is safe to rerun: it performs only ID-based upserts, never removes an
index or existing document. Stale documents are reported and cause failure.
"""
from __future__ import annotations

import sys
from pathlib import Path

# docker exec starts a new process using the image's environment, not the
# PYTHONPATH exported by entrypoint.sh. Locate the mounted release ourselves
# so the deploy transaction works regardless of the caller's working directory.
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "backend"))

from elasticsearch.helpers import scan
from knowledge_base_runtime.backend.service import retrieval_index


class IndexCheckError(Exception):
    """A sanitized failure message generated by this script."""


def synchronize() -> tuple[int, int, int]:
    if not retrieval_index.ELASTICSEARCH_ENABLED:
        raise IndexCheckError("Elasticsearch 未启用")

    papers = retrieval_index._fetch_papers()
    if not papers:
        raise IndexCheckError("数据库没有活动论文，拒绝将空索引视为成功")
    ids = [str(paper.get("id") or "").strip() for paper in papers]
    if not all(ids) or len(set(ids)) != len(ids):
        raise IndexCheckError("数据库论文 ID 为空或重复")

    synced, failed, errors = retrieval_index._bulk_upsert_elasticsearch(
        papers, batch_size=500, recreate=False
    )
    if failed or errors or synced != len(papers):
        raise IndexCheckError(f"关键词索引写入不完整：成功 {synced}，失败 {failed}")

    client = retrieval_index.elasticsearch_client()
    count_response = client.count(index=retrieval_index.ELASTICSEARCH_INDEX)
    count_body = getattr(count_response, "body", count_response)
    indexed_count = int(count_body["count"])
    indexed_ids = {
        str(hit["_id"])
        for hit in scan(
            client,
            index=retrieval_index.ELASTICSEARCH_INDEX,
            query={"query": {"match_all": {}}, "_source": False},
            size=500,
            raise_on_error=True,
        )
    }
    active_ids = set(ids)
    missing = len(active_ids - indexed_ids)
    stale = len(indexed_ids - active_ids)
    if missing or stale or indexed_count != len(indexed_ids):
        raise IndexCheckError(
            f"关键词索引校验失败：数据库 {len(active_ids)} 条，"
            f"索引 {indexed_count} 条，缺失 {missing} 条，过期 {stale} 条；"
            "未删除任何索引或数据，请检查后处理"
        )
    return len(active_ids), indexed_count, stale


def main() -> int:
    try:
        active_count, indexed_count, _ = synchronize()
    except IndexCheckError as exc:
        print(f"[zhiyan] {exc}", file=sys.stderr)
        return 1
    except Exception as exc:
        # Backend exceptions can contain connection credentials or source data.
        print(f"[zhiyan] 关键词索引建立失败：{type(exc).__name__}；请检查数据库和搜索服务", file=sys.stderr)
        return 1
    print(f"[zhiyan] 关键词索引已核对：活动论文 {active_count} 条，索引 {indexed_count} 条")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
